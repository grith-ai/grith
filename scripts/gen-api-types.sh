  limit?: number;
  offset?: number;
  /// `"full"` (default) returns only proxy-decision rows. `"all"`
  /// includes compact short-circuit rows from session-allowed and
  /// noise-path paths.
  include?: "full" | "all";
}

export type AuditExportFormat = "json" | "csv";

