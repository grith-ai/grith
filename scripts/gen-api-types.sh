#!/usr/bin/env bash
# gen-api-types.sh — Generate TypeScript types from Rust API structures
#
# Generates TypeScript interfaces that mirror the Rust types used in the
# grith HTTP/WebSocket API. This is a stopgap until ts-rs or a similar
# crate automates generation from Rust derive macros.
#
# Usage:
#   ./scripts/gen-api-types.sh
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
DASHBOARD_DIR="${PROJECT_ROOT}/dashboard"
TYPES_DIR="${DASHBOARD_DIR}/src/types"
OUTPUT_FILE="${TYPES_DIR}/api.ts"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
info()  { printf "\033[1;34m[info]\033[0m  %s\n" "$*"; }
ok()    { printf "\033[1;32m[ok]\033[0m    %s\n" "$*"; }
err()   { printf "\033[1;31m[error]\033[0m %s\n" "$*" >&2; }

# ---------------------------------------------------------------------------
# Preflight checks
# ---------------------------------------------------------------------------
if [[ ! -d "${DASHBOARD_DIR}" ]]; then
    info "Dashboard directory not found at ${DASHBOARD_DIR}. Creating it..."
    mkdir -p "${DASHBOARD_DIR}/src"
fi

mkdir -p "${TYPES_DIR}"

# ---------------------------------------------------------------------------
# Generate types
# ---------------------------------------------------------------------------
info "Generating TypeScript types..."

cat > "${OUTPUT_FILE}" << 'TYPESCRIPT'
/**
 * TypeScript types mirroring the Rust API types.
 *
 * AUTO-GENERATED by `scripts/gen-api-types.sh` — do not edit manually.
 * Run that script (or the CI type-drift check) to regenerate after changing
 * any Rust API struct in the `grith-*` crates.
 */

