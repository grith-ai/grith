    #[test]
    fn cname_chain_seeds_only_reachable_address_with_bounded_ttl() {
        let mut packet = build_dns_query("alias.example", 1);
        packet[2] = 0x81;
        packet[3] = 0x80;
        packet[6..8].copy_from_slice(&2u16.to_be_bytes());

        // alias.example CNAME target.example, TTL 120
        packet.extend_from_slice(&[0xC0, 0x0C, 0x00, 0x05, 0x00, 0x01]);
        packet.extend_from_slice(&120u32.to_be_bytes());
        let mut target_name = Vec::new();
        target_name.push(6);
        target_name.extend_from_slice(b"target");
        target_name.push(7);
        target_name.extend_from_slice(b"example");
        target_name.push(0);
        packet.extend_from_slice(&(target_name.len() as u16).to_be_bytes());
        packet.extend_from_slice(&target_name);

        // target.example A 192.0.2.44, TTL 300
        packet.extend_from_slice(&target_name);
        packet.extend_from_slice(&[0x00, 0x01, 0x00, 0x01]);
        packet.extend_from_slice(&300u32.to_be_bytes());
        packet.extend_from_slice(&[0x00, 0x04, 192, 0, 2, 44]);

        let parsed = parse_response(&packet).unwrap();
        assert_eq!(parsed.domain, "alias.example");
        assert_eq!(
            parsed.answers,
            vec![DnsAnswer {
                ip: "192.0.2.44".parse().unwrap(),
                ttl: Duration::from_secs(120),
            }]
        );
    }
