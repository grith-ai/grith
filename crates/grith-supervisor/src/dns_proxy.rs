//! Shared DNS wire-format parsing for in-line and connected-proxy inspection.
//!
//! Unconnected explicit-destination datagrams remain in-line: the query is
//! parsed from the send buffer and matching responses populate the cache.
//! Feature-gated connected UDP/53 sockets use the same strict parsers in a
//! per-socket managed proxy route so ordinary `write`/`read` calls need not be
//! trapped.
//!
//! Parsing the QNAME closes the DNS exfiltration gap where an attacker encodes
//! secrets in subdomain labels (e.g., `AKIA1234.attacker.com`) and leaks data
//! purely through DNS lookups.

use std::collections::{HashMap, HashSet};
use std::net::{IpAddr, Ipv4Addr, Ipv6Addr};
use std::time::Duration;

/// Parsed metadata for one outbound DNS query.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ParsedQuery {
    pub id: u16,
    pub domain: String,
    pub qtype: u16,
    pub query_type: String,
}

/// One address reached by the response's QNAME/CNAME chain.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct DnsAnswer {
    pub ip: IpAddr,
    pub ttl: Duration,
}

/// A validated DNS response suitable for transaction correlation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ParsedResponse {
    pub id: u16,
    pub domain: String,
    pub qtype: u16,
    pub answers: Vec<DnsAnswer>,
}

/// DNS response codes generated by the connected-UDP inspection proxy.
///
/// Keeping response construction in the wire-format module ensures the
/// in-line and proxy transports do not grow subtly different DNS encoders.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum DnsErrorCode {
    FormErr = 1,
    ServFail = 2,
    Refused = 5,
}

fn read_u16(packet: &[u8], offset: usize) -> Option<u16> {
    let bytes: [u8; 2] = packet.get(offset..offset + 2)?.try_into().ok()?;
    Some(u16::from_be_bytes(bytes))
}

fn read_u32(packet: &[u8], offset: usize) -> Option<u32> {
    let bytes: [u8; 4] = packet.get(offset..offset + 4)?.try_into().ok()?;
    Some(u32::from_be_bytes(bytes))
}

/// Decode a DNS name, including response compression, with cycle and bounds
/// checks. The returned offset is in the original (non-jumped) stream.
fn parse_name(packet: &[u8], start: usize, allow_compression: bool) -> Option<(String, usize)> {
    let mut labels = Vec::new();
    let mut cursor = start;
    let mut resume = None;
    let mut visited = HashSet::new();
    let mut wire_len = 0usize;

    loop {
        if !visited.insert(cursor) || visited.len() > 128 {
            return None;
        }
        let len = *packet.get(cursor)?;
        if len & 0xC0 == 0xC0 {
            if !allow_compression {
                return None;
            }
            let low = *packet.get(cursor + 1)? as usize;
            let target = (((len as usize) & 0x3F) << 8) | low;
            if target >= packet.len() {
                return None;
            }
            resume.get_or_insert(cursor + 2);
            cursor = target;
            continue;
        }
        if len & 0xC0 != 0 {
            return None;
        }
        cursor += 1;
        if len == 0 {
            break;
        }
        let len = len as usize;
        if len > 63 {
            return None;
        }
        let raw = packet.get(cursor..cursor + len)?;
        let label = std::str::from_utf8(raw).ok()?;
        if label.is_empty()
            || !label
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
        {
            return None;
        }
        wire_len = wire_len.checked_add(len + 1)?;
        if wire_len > 254 {
            return None;
        }
        labels.push(label.to_string());
        cursor += len;
    }

    if labels.is_empty() {
        return None;
    }
    Some((labels.join("."), resume.unwrap_or(cursor)))
}

/// Advance over a DNS name without interpreting its labels.
///
/// Resource-record owner names may legitimately be the root name (notably the
/// EDNS OPT pseudo-record), while QNAMEs used for policy must remain non-empty.
fn skip_name(packet: &[u8], start: usize, allow_compression: bool) -> Option<usize> {
    let mut cursor = start;
    let mut resume = None;
    let mut visited = HashSet::new();

    loop {
        if !visited.insert(cursor) || visited.len() > 128 {
            return None;
        }
        let len = *packet.get(cursor)?;
        if len & 0xC0 == 0xC0 {
            if !allow_compression {
                return None;
            }
            let low = *packet.get(cursor + 1)? as usize;
            let target = (((len as usize) & 0x3F) << 8) | low;
            if target >= packet.len() {
                return None;
            }
            resume.get_or_insert(cursor + 2);
            cursor = target;
            continue;
        }
        if len & 0xC0 != 0 || len > 63 {
            return None;
        }
        cursor += 1;
        if len == 0 {
            return Some(resume.unwrap_or(cursor));
        }
        cursor = cursor.checked_add(len as usize)?;
        packet.get(..cursor)?;
    }
}

fn skip_resource_records(packet: &[u8], mut offset: usize, count: usize) -> Option<usize> {
    for _ in 0..count {
        offset = skip_name(packet, offset, true)?;
        let rdlength = read_u16(packet, offset + 8)? as usize;
        offset = offset.checked_add(10)?.checked_add(rdlength)?;
        packet.get(..offset)?;
    }
    Some(offset)
}

/// Strictly parse a single-question outbound DNS packet.
pub(crate) fn parse_query(packet: &[u8]) -> Option<ParsedQuery> {
    if packet.len() < 12 {
        return None;
    }
    let flags = read_u16(packet, 2)?;
    let qdcount = read_u16(packet, 4)?;
    // Query (QR=0), standard opcode, exactly one question.
    if flags & 0x8000 != 0 || flags & 0x7800 != 0 || flags & 0x0040 != 0 || qdcount != 1 {
        return None;
    }
    let (domain, offset) = parse_name(packet, 12, false)?;
    let qtype = read_u16(packet, offset)?;
    let qclass = read_u16(packet, offset + 2)?;
    if qclass != 1 {
        return None;
    }
    let record_count = (read_u16(packet, 6)? as usize)
        .checked_add(read_u16(packet, 8)? as usize)?
        .checked_add(read_u16(packet, 10)? as usize)?;
    let question_end = offset.checked_add(4)?;
    if skip_resource_records(packet, question_end, record_count)? != packet.len() {
        return None;
    }
    Some(ParsedQuery {
        id: read_u16(packet, 0)?,
        domain,
        qtype,
        query_type: qtype_to_string(qtype),
    })
}

/// Return whether a parsed response belongs to `query`.
///
/// Transaction IDs alone are not sufficient: clients may reuse an ID while
/// multiple questions are outstanding. Match the complete question tuple and
/// compare names case-insensitively, as DNS names are case-insensitive.
pub(crate) fn response_matches_query(query: &ParsedQuery, response: &ParsedResponse) -> bool {
    query.id == response.id
        && query.qtype == response.qtype
        && query.domain.eq_ignore_ascii_case(&response.domain)
}

/// Parse `packet` as a response and require an exact transaction/question
/// match with `query`.
pub(crate) fn parse_matching_response(
    packet: &[u8],
    query: &ParsedQuery,
) -> Option<ParsedResponse> {
    let response = parse_response(packet)?;
    response_matches_query(query, &response).then_some(response)
}

/// Build a DNS error response which preserves only a valid original question.
///
/// For a malformed query, a minimal header carrying the transaction ID (when
/// present) is returned. For a valid query, the exact question bytes are
/// echoed. Answer, authority and additional counts are always zero, so no
/// unvalidated bytes are reflected as records.
pub(crate) fn build_error_response(query: &[u8], code: DnsErrorCode) -> Vec<u8> {
    let mut response = vec![0u8; 12];
    if let Some(id) = query.get(..2) {
        response[..2].copy_from_slice(id);
    }

    let request_flags = read_u16(query, 2).unwrap_or_default();
    // Preserve the opcode, RD and CD bits. Set QR and the requested RCODE;
    // AA/TC/RA/AD/Z are deliberately clear because this proxy is not an
    // authoritative or recursive resolver itself.
    let flags = 0x8000 | (request_flags & 0x7910) | code as u16;
    response[2..4].copy_from_slice(&flags.to_be_bytes());

    if parse_query(query).is_some() {
        if let Some((_, name_end)) = parse_name(query, 12, false) {
            if let Some(question_end) = name_end.checked_add(4) {
                if let Some(question) = query.get(12..question_end) {
                    response[4..6].copy_from_slice(&1u16.to_be_bytes());
                    response.extend_from_slice(question);
                }
            }
        }
    }
    response
}

pub(crate) fn build_formerr_response(query: &[u8]) -> Vec<u8> {
    build_error_response(query, DnsErrorCode::FormErr)
}

pub(crate) fn build_servfail_response(query: &[u8]) -> Vec<u8> {
    build_error_response(query, DnsErrorCode::ServFail)
}

pub(crate) fn build_refused_response(query: &[u8]) -> Vec<u8> {
    build_error_response(query, DnsErrorCode::Refused)
}

/// Parse A and AAAA resource records from a DNS response packet.
///
/// Extracts IP addresses from answer section records. Only parses
/// type A (1) and AAAA (28) records. Returns an empty vec on any
/// parse failure.
#[cfg(test)]
pub(crate) fn parse_response_ips(packet: &[u8]) -> Vec<IpAddr> {
    parse_response(packet)
        .map(|response| {
            response
                .answers
                .into_iter()
                .map(|answer| answer.ip)
                .collect()
        })
        .unwrap_or_default()
}

/// Parse a response and retain only A/AAAA records reachable from the
/// question through zero or more CNAME records.
pub(crate) fn parse_response(packet: &[u8]) -> Option<ParsedResponse> {
    if packet.len() < 12 {
        return None;
    }
    let flags = read_u16(packet, 2)?;
    let qdcount = read_u16(packet, 4)? as usize;
    let ancount = read_u16(packet, 6)? as usize;
    let nscount = read_u16(packet, 8)? as usize;
    let arcount = read_u16(packet, 10)? as usize;
    if flags & 0x8000 == 0 || flags & 0x7800 != 0 || flags & 0x0040 != 0 || qdcount != 1 {
        return None;
    }

    let (domain, mut offset) = parse_name(packet, 12, true)?;
    let qtype = read_u16(packet, offset)?;
    if read_u16(packet, offset + 2)? != 1 {
        return None;
    }
    offset += 4;
    if flags & 0x0200 != 0 {
        offset = skip_resource_records(packet, offset, ancount + nscount + arcount)?;
        if offset != packet.len() {
            return None;
        }
        return Some(ParsedResponse {
            id: read_u16(packet, 0)?,
            domain,
            qtype,
            answers: Vec::new(),
        });
    }
    if flags & 0x000F != 0 {
        offset = skip_resource_records(packet, offset, ancount + nscount + arcount)?;
        if offset != packet.len() {
            return None;
        }
        return Some(ParsedResponse {
            id: read_u16(packet, 0)?,
            domain,
            qtype,
            answers: Vec::new(),
        });
    }

    let mut cnames: HashMap<String, (String, u32)> = HashMap::new();
    let mut addresses: HashMap<String, Vec<(IpAddr, u32)>> = HashMap::new();
    for _ in 0..ancount {
        let (owner, next) = parse_name(packet, offset, true)?;
        let owner = owner.to_ascii_lowercase();
        offset = next;
        let rtype = read_u16(packet, offset)?;
        let class = read_u16(packet, offset + 2)?;
        let ttl = read_u32(packet, offset + 4)?;
        let rdlength = read_u16(packet, offset + 8)? as usize;
        offset += 10;
        let rdata_end = offset.checked_add(rdlength)?;
        packet.get(offset..rdata_end)?;

        if class == 1 {
            match rtype {
                1 if rdlength == 4 => {
                    let bytes = packet.get(offset..offset + 4)?;
                    addresses.entry(owner).or_default().push((
                        IpAddr::V4(Ipv4Addr::new(bytes[0], bytes[1], bytes[2], bytes[3])),
                        ttl,
                    ));
                }
                28 if rdlength == 16 => {
                    let octets: [u8; 16] = packet.get(offset..offset + 16)?.try_into().ok()?;
                    addresses
                        .entry(owner)
                        .or_default()
                        .push((IpAddr::V6(Ipv6Addr::from(octets)), ttl));
                }
                5 => {
                    let (target, consumed) = parse_name(packet, offset, true)?;
                    if consumed != rdata_end {
                        return None;
                    }
                    cnames.insert(owner, (target.to_ascii_lowercase(), ttl));
                }
                _ => {}
            }
        }
        offset = rdata_end;
    }
    offset = skip_resource_records(packet, offset, nscount + arcount)?;
    if offset != packet.len() {
        return None;
    }

    let mut current = domain.to_ascii_lowercase();
    let mut chain_ttl = u32::MAX;
    let mut seen = HashSet::new();
    for _ in 0..32 {
        if !seen.insert(current.clone()) {
            return None;
        }
        if let Some(records) = addresses.get(&current) {
            let answers = records
                .iter()
                .map(|(ip, ttl)| DnsAnswer {
                    ip: *ip,
                    ttl: Duration::from_secs((*ttl).min(chain_ttl) as u64),
                })
                .collect();
            return Some(ParsedResponse {
                id: read_u16(packet, 0)?,
                domain,
                qtype,
                answers,
            });
        }
        let Some((target, ttl)) = cnames.get(&current) else {
            return Some(ParsedResponse {
                id: read_u16(packet, 0)?,
                domain,
                qtype,
                answers: Vec::new(),
            });
        };
        chain_ttl = chain_ttl.min(*ttl);
        current = target.clone();
    }
    None
}

